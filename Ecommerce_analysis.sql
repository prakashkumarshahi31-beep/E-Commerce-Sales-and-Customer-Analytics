 -- Topic Case When/ Business Segmentation
 
 -- Q Categorise Customer based on their total spending
 SELECT
    customer_name,
    SUM(total_amount) AS total_spending,
    CASE
        WHEN SUM(total_amount) < 10000 THEN 'Low Spending'
        WHEN SUM(total_amount) <= 50000 THEN 'Medium Spending'
        ELSE 'High Spending'
    END AS spending_category
FROM orders
GROUP BY customer_name;


-- Q Categorise orders based on quantity
select 
  order_id,
  count(quantity),
  case
     when count(quantity)<10 then 'small order'
     when count(quantity)>20 then 'medium order'
     else 'large order'
  end as quantity
from order_items
group by order_id;



-- Topic  Cte and Subqueries

-- Q Find customer whose spending is higher than the Average customer spending
with customer_spending as(
  select
     customer_id,
     sum(total_amount) as total_spending
  from orders
  group by customer_id
)
select customer_id,total_spending
from customer_spending
where total_spending>(
  select avg(total_spending)
  from customer_spending
);


-- Q Find order_id of those product whose quantity are higher than Average quantity

with product as(
  select
     order_id,
     sum(quantity) as total_quantity
  from order_items
  group by order_id
)
select order_id,total_quantity
from product
where total_quantity>(
  select avg(quantity) 
  from product
);


-- Topic Window Functions

-- Q Rank product by revenue within each category
select
  customer_name,
  product,
  total_amount,
  rank() over(partition by product order by total_amount) as total_rank
from orders;

-- Q Find the monthly revenue overtime
 select 
   customer_name,
   order_date,
   total_amount,
   lag(total_amount) over(partition by order_date order by total_amount) as monthly_revenue
from orders;
